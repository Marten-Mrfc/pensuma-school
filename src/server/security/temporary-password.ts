/**
 * Four words and two digits, e.g. "tafel-wolk-trein-zeil-47" (about 32
 * bits, easy to read aloud). Teachers must replace it at first sign-in.
 */
export function generateTemporaryPassword(): string {
  const words = Array.from({ length: 4 }, () => WORDS[randomInt(WORDS.length)]);
  return `${words.join("-")}-${randomInt(10, 100)}`;
}
